// Regenerates assets/permeability-data.js from data/permeability-coefficients.csv.
//
// The CSV is the source of truth for the material reference library (add a
// row, add a temperature column — whatever you have data for). Run this
// script after editing the CSV, then `npm run build` to refresh the
// standalone bundle too.
//
// Expected CSV shape (semicolon-delimited, comma as decimal separator,
// matching the convention of the datasheets this data comes from):
//
//   NAme;Unit;20C;40C;60C;100C
//   Freundeberg EPDM910;[cm3(NTP)*mm/(m2*h*bar)];0,94;;;
//
// An empty cell means "no data at that temperature" and is omitted.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = dirname(fileURLToPath(import.meta.url));
const csvPath = join(root, "data/permeability-coefficients.csv");

// Maps a CSV "Unit" column label (brackets/whitespace stripped) to the
// permeabilityUnit key used by assets/calc.js's PERMEABILITY_UNITS table.
const UNIT_LABEL_TO_KEY = {
  "cm3(NTP)*mm/(m2*h*bar)": "ntp_hour_bar",
  "cm3(STP)*mm/(m2*day*bar)": "practical_bar",
  "cm3(STP)*mm/(m2*day*atm)": "practical",
  "cm3(STP)*mm/(mm2*day*bar)": "practical_mm2_bar",
  "cm3(STP)*cm/(cm2*s*cmHg)": "traditional",
  barrer: "barrer",
};

function parseNumber(cell) {
  const trimmed = cell.trim();
  if (trimmed === "") return null;
  const normalized = trimmed.replace(",", ".");
  const value = Number(normalized);
  if (!Number.isFinite(value)) {
    throw new Error(`Could not parse numeric cell: "${cell}"`);
  }
  return value;
}

function resolveUnitKey(label) {
  const normalized = label.trim().replace(/^\[|\]$/g, "");
  const key = UNIT_LABEL_TO_KEY[normalized];
  if (!key) {
    throw new Error(
      `Unrecognized permeability unit label "${label}" in ${csvPath}. ` +
        `Add a mapping for it in UNIT_LABEL_TO_KEY in generate-permeability-data.js.`
    );
  }
  return key;
}

const csv = readFileSync(csvPath, "utf8");
const lines = csv.split(/\r\n|\n/).filter((line) => line.trim() !== "");
const [headerLine, ...dataLines] = lines;
const header = headerLine.split(";");
const tempColumns = header.slice(2).map((col) => {
  const match = col.trim().match(/^(\d+(?:\.\d+)?)C$/);
  if (!match) {
    throw new Error(`Could not parse temperature column header: "${col}"`);
  }
  return Number(match[1]);
});

const materials = dataLines.map((line) => {
  const cells = line.split(";");
  const name = cells[0].trim();
  const unitKey = resolveUnitKey(cells[1]);
  const temperaturesC = {};
  tempColumns.forEach((tempC, i) => {
    const value = parseNumber(cells[2 + i] ?? "");
    if (value != null) temperaturesC[tempC] = value;
  });
  return { name, unitKey, temperaturesC };
});

const out = `// Generated by generate-permeability-data.js from
// data/permeability-coefficients.csv — do not edit by hand, edit the CSV
// and re-run \`npm run generate-data\` instead.

export const PERMEABILITY_DATA = ${JSON.stringify(materials, null, 2)};
`;

writeFileSync(join(root, "assets/permeability-data.js"), out);
console.log(`Wrote assets/permeability-data.js (${materials.length} materials)`);
